@lru_cache(maxsize=1)
def load_activities() -> tuple[Any, ...]:
    """加载并缓存活动库。

    第一次调用时做完整 Pydantic 校验 —— 这一步不能省：厂商的 schema 保证是
    服务端契约，而这里是我们自己的数据契约。50 条数据里有任何一条引用错了词表，
    应该在这里炸掉，而不是等到规划时 LLM 拿到一个不存在的 activity_id。
    """
    from activities import Activity
    return tuple(Activity(**a) for a in ACTIVITIES)


def get(activity_id: str):
    for a in load_activities():
        if a.activity_id == activity_id:
            return a
    return None


